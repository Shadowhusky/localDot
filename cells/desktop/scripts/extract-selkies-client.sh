#!/usr/bin/env bash
# Copies Selkies' dashboard (index.html, assets, icons, the MPL-2.0 text) out of the pinned base
# image into <dest>, using the selkies-client build stage so no container runs and nothing is
# bind-mounted. <dest> is replaced, so it must lie strictly inside this repository and be either
# missing or a previous extraction.
set -euo pipefail
raw=${1:?usage: extract-selkies-client.sh <dest>}
root="$(cd "$(dirname "$0")/../../.." && pwd -P)"
home="$(cd "$HOME" && pwd -P)"
if [ ! -f "$root/cells/desktop/Dockerfile" ]; then
  echo "extract-selkies-client.sh: refusing: $root/cells/desktop/Dockerfile is missing, so $root is not this repository" >&2
  exit 1
fi
# Resolve <dest> without creating anything: its deepest existing ancestor physically, the rest as
# written, which may not step through "." or "..".
base=$raw
rest=
until [ -d "$base" ]; do
  rest="/$(basename "$base")$rest"
  base="$(dirname "$base")"
done
dest="$(cd "$base" && pwd -P)$rest"
case "$rest/" in */./* | */../*) dest=/ ;; esac
case "$dest" in
  / | "$home" | "$root") ok=no ;;
  "$root"/*) ok=yes ;;
  *) ok=no ;;
esac
if [ "$ok" != yes ]; then
  echo "extract-selkies-client.sh: refusing to replace $raw: <dest> must be inside $root" >&2
  exit 1
fi
# A previous extraction holds Selkies' core bundle, assets/selkies-core-<hash>.js; index.html and
# assets/ alone are the shape of any web build.
extracted() {
  local f
  for f in "$1"/assets/selkies-core-*.js; do
    if [ -f "$f" ] && [ ! -L "$f" ]; then return 0; fi
  done
  return 1
}
if { [ -e "$dest" ] || [ -L "$dest" ]; } && ! { [ -d "$dest" ] && [ ! -L "$dest" ] && extracted "$dest"; }; then
  echo "extract-selkies-client.sh: refusing to replace $raw: it is not a previous extraction (assets/selkies-core-*.js)" >&2
  exit 1
fi
cd "$(dirname "$0")/.."
rm -rf "$dest"
docker build --target selkies-client --output "type=local,dest=$dest" .
# manifest.json is generated by the cell's nginx at runtime and does not exist here.
sed -i.orig 's#<link rel="manifest" href="manifest.json" crossorigin="use-credentials">##' "$dest/index.html"
rm -f "$dest/index.html.orig"
if grep -q 'rel="manifest"' "$dest/index.html"; then
  echo "extract-selkies-client.sh: the manifest link survived the sed; update its pattern" >&2
  exit 1
fi
ls "$dest/index.html" "$dest/assets" "$dest/icon.png" "$dest/icon-512.png" "$dest/LICENSE" >/dev/null
if ! extracted "$dest"; then
  echo "extract-selkies-client.sh: no assets/selkies-core-*.js in the build; the next run would refuse $raw" >&2
  exit 1
fi
echo "extracted Selkies client to $dest"
