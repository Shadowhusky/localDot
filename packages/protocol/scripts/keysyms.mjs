// Writes src/keysyms.ts from xorgproto's keysymdef.h and XF86keysym.h:
//   node scripts/keysyms.mjs /path/to/include/X11 <xorgproto version>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [dir, version] = process.argv.slice(2);
if (!dir || !version) throw new Error("usage: keysyms.mjs <include/X11 dir> <xorgproto version>");

const EVDEV_BASE = 0x10081000;
const header = readFileSync(join(dir, "keysymdef.h"), "utf8");
const notice = header
  .slice(header.indexOf("/*") + 2, header.indexOf("*/"))
  .replace(/^\*+\n|\*+$/g, "")
  .trim();
const entries = [];
for (const [file, prefix, named] of [
  ["keysymdef.h", "XK_", ""],
  ["XF86keysym.h", "XF86XK_", "XF86"],
]) {
  const define = new RegExp(
    `^#define ${prefix}(\\w+)\\s+(?:0x([0-9a-fA-F]+)|_EVDEVK\\(0x([0-9a-fA-F]+)\\))`,
  );
  for (const line of readFileSync(join(dir, file), "utf8").split("\n")) {
    const m = define.exec(line);
    if (!m || m[1] === "VoidSymbol") continue;
    const value = m[2] ? Number.parseInt(m[2], 16) : EVDEV_BASE + Number.parseInt(m[3], 16);
    entries.push(`${named}${m[1]} ${value.toString(16)}`);
  }
}

const lines = [];
let line = "";
for (const entry of entries) {
  if (line && line.length + entry.length + 1 > 98) {
    lines.push(line);
    line = "";
  }
  line = line ? `${line} ${entry}` : entry;
}
if (line) lines.push(line);

writeFileSync(
  new URL("../src/keysyms.ts", import.meta.url),
  `// Every X keysym name and its value, in xorgproto ${version}'s order (keysymdef.h, then
// XF86keysym.h): "name hex" pairs. Generated by scripts/keysyms.mjs; do not edit.
/*
${notice}
*/
export const KEYSYM_TABLE = \`
${lines.join("\n")}
\`;
`,
);
console.log(`${entries.length} keysyms`);
