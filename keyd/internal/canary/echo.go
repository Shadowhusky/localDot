// Package canary provides the isolated synthetic upstream for installed diagnostics.
// It is not a route or dial exception in the ordinary keyd service.
package canary

import (
	"bufio"
	"bytes"
	"context"
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"errors"
	"io"
	"math/big"
	"net"
	"net/http"
	"sync"
	"time"
)

const Host = "canary.localdot.invalid"
const lifetime = 8 * time.Second

var errRefused = errors.New("canary upstream unavailable")

// Echo accepts only the fixed diagnostic authority. Every connection is a net.Pipe:
// there is no socket, DNS lookup, network fallback, account credential or Keychain access.
// The future diagnostic runner supplies this dialer only to its isolated canary gateway.
type Echo struct {
	secret                            string
	challenge                         string
	tls                               *tls.Config
	roots                             *x509.CertPool
	mu                                sync.Mutex
	closed                            bool
	started, authenticated, reflected int
	active                            map[net.Conn]net.Conn
	workers                           sync.WaitGroup
}

type Receipt struct {
	Started       int  `json:"started"`
	Authenticated int  `json:"authenticated"`
	Reflected     int  `json:"reflected"`
	Active        int  `json:"active"`
	Closed        bool `json:"closed"`
}

func NewEcho() (*Echo, error) {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, errRefused
	}
	var random [64]byte
	if _, err := rand.Read(random[:]); err != nil {
		return nil, errRefused
	}
	now := time.Now()
	cert := &x509.Certificate{
		SerialNumber: new(big.Int).SetBytes(random[:16]),
		Subject:      pkix.Name{CommonName: Host}, DNSNames: []string{Host},
		NotBefore: now.Add(-time.Minute), NotAfter: now.Add(time.Hour),
		KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	der, err := x509.CreateCertificate(rand.Reader, cert, cert, &key.PublicKey, key)
	if err != nil {
		return nil, errRefused
	}
	parsed, err := x509.ParseCertificate(der)
	if err != nil {
		return nil, errRefused
	}
	roots := x509.NewCertPool()
	roots.AddCert(parsed)
	config := &tls.Config{Certificates: []tls.Certificate{{Certificate: [][]byte{der}, PrivateKey: key}}, MinVersion: tls.VersionTLS12, NextProtos: []string{"http/1.1"}}
	config.GetConfigForClient = func(hello *tls.ClientHelloInfo) (*tls.Config, error) {
		if hello.ServerName != Host {
			return nil, errRefused
		}
		return nil, nil
	}
	return &Echo{
		secret:    "canary-" + hex.EncodeToString(random[16:48]),
		challenge: hex.EncodeToString(random[48:]), tls: config, roots: roots,
		active: make(map[net.Conn]net.Conn),
	}, nil
}

// SyntheticSecret is generated by this instance; callers cannot insert user credentials.
func (e *Echo) SyntheticSecret() string { return e.secret }
func (e *Echo) Path() string            { return "/v1/canary/" + e.challenge }
func (e *Echo) Challenge() string       { return e.challenge }
func (e *Echo) RootCAs() *x509.CertPool { return e.roots.Clone() }

func (e *Echo) DialContext(ctx context.Context, network, address string) (net.Conn, error) {
	if ctx.Err() != nil || network != "tcp" || (address != Host+":443" && address != Host+".:443") {
		return nil, errRefused
	}
	e.mu.Lock()
	defer e.mu.Unlock()
	if e.closed || ctx.Err() != nil || len(e.active) >= 4 || e.started >= 16 {
		return nil, errRefused
	}
	client, server := net.Pipe()
	deadline := time.Now().Add(lifetime)
	_ = client.SetDeadline(deadline)
	_ = server.SetDeadline(deadline)
	e.active[server] = client
	e.started++
	e.workers.Add(1)
	go e.serve(ctx, server, client)
	return client, nil
}

func (e *Echo) serve(ctx context.Context, raw, client net.Conn) {
	defer e.workers.Done()
	defer func() {
		_ = raw.Close()
		_ = client.Close()
		e.mu.Lock()
		delete(e.active, raw)
		e.mu.Unlock()
	}()
	stop := context.AfterFunc(ctx, func() { _ = raw.Close(); _ = client.Close() })
	defer stop()
	conn := tls.Server(raw, e.tls)
	if err := conn.HandshakeContext(ctx); err != nil {
		return
	}
	// A single bounded request; never a general-purpose echo or keep-alive service.
	request, err := http.ReadRequest(bufio.NewReader(io.LimitReader(conn, 16*1024)))
	if err != nil {
		return
	}
	defer request.Body.Close()
	if request.Method != "GET" || request.Host != Host || request.RequestURI != e.Path() ||
		request.ContentLength != 0 || len(request.TransferEncoding) != 0 {
		writeResponse(conn, 400, []byte("invalid diagnostic request"), "")
		return
	}
	values := request.Header.Values("Authorization")
	if len(values) != 1 || values[0] != "Bearer "+e.secret {
		writeResponse(conn, 401, []byte("diagnostic authentication refused"), "")
		return
	}
	e.mu.Lock()
	e.authenticated++
	e.mu.Unlock()
	// Deliberately reflect raw and encoded fake values. Real keyd must substitute on the
	// request, scrub this header/body, and preserve the challenge on the return path.
	body, err := json.Marshal(map[string]string{
		"challenge": e.challenge, "authorization": values[0],
		"base64": base64.StdEncoding.EncodeToString([]byte(e.secret)),
		"hex":    hex.EncodeToString([]byte(e.secret)),
	})
	if err != nil {
		return
	}
	if writeResponse(conn, 200, body, e.secret) == nil {
		e.mu.Lock()
		e.reflected++
		e.mu.Unlock()
	}
}

func writeResponse(conn net.Conn, status int, body []byte, secret string) error {
	header := http.Header{"Content-Type": {"application/json"}, "Cache-Control": {"no-store"}}
	if secret != "" {
		header.Set("X-Canary-Key", secret)
	}
	response := &http.Response{StatusCode: status, ProtoMajor: 1, ProtoMinor: 1, Header: header,
		ContentLength: int64(len(body)), Body: io.NopCloser(bytes.NewReader(body)), Close: true}
	return response.Write(conn)
}

func (e *Echo) Receipt() Receipt {
	e.mu.Lock()
	defer e.mu.Unlock()
	return Receipt{e.started, e.authenticated, e.reflected, len(e.active), e.closed}
}

// Close rejects further dials and drains every TLS worker, including stalled handshakes.
func (e *Echo) Close() {
	e.mu.Lock()
	e.closed = true
	for server, client := range e.active {
		_ = server.Close()
		_ = client.Close()
	}
	e.mu.Unlock()
	e.workers.Wait()
}
